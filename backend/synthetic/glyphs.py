def _parse(spec: str):
    advance, _, body = spec.partition(";")
    strokes = []
    for part in body.split("|"):
        part = part.strip()
        if not part:
            continue
        kind, *points = part.split()
        strokes.append((kind, [tuple(float(v) for v in p.split(",")) for p in points]))
    return float(advance), strokes


GLYPHS = {key: _parse(spec) for key, spec in _SPEC.items()}
CHARSET = frozenset(k for k in GLYPHS if "~" not in k)


def base_char(key: str) -> str:
    """The character a glyph key stands for: "1~7" is a 1."""
    return key.split("~", 1)[0] if len(key) > 1 else key


def unsupported(text: str) -> set[str]:
    return set(text) - CHARSET
